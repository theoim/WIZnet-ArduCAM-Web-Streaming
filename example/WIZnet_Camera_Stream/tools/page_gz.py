#!/usr/bin/env python3
"""
Build step: web/index.html -> a gzip'd C array the firmware serves as is.

    page_gz.py <index.html> <out.h> <out.html> [NAME=0|1 ...]

What it does to the source, in this order:

  - "/* @if NAME */" ... "/* @endif */" keeps or drops the lines between,
    by the NAME=0|1 arguments (an unknown NAME is an error, not a 0).
  - A comment that has whole lines to itself - starting a line with "/*" or
    "<!--" and closing at the end of a line - is a note for whoever edits the
    page and is dropped. A comment that shares a line with code is page
    content and stays, so nothing inside a style rule or a script changes.
  - gzip -9 with the timestamp fixed at 0, so the same page gives the same
    bytes and an image rebuilt from the same commit is the same image.

out.html is the page after the first two steps - what the browser gets once
it has unzipped - for checking the script with "node --check" and the like.
"""
import gzip, re, sys

IF_RE    = re.compile(r"^\s*/\*\s*@if\s+(\w+)\s*\*/\s*$")
ENDIF_RE = re.compile(r"^\s*/\*\s*@endif\s*\*/\s*$")


def strip(lines, defs, path):
    out, keep, skip_until = [], [], None
    for no, line in enumerate(lines, 1):
        if skip_until:
            if skip_until in line:
                if not line.rstrip().endswith(skip_until):
                    sys.exit(f"{path}:{no}: code after the end of a whole-line comment")
                skip_until = None
            continue
        m = IF_RE.match(line)
        if m:
            if m.group(1) not in defs:
                sys.exit(f"{path}:{no}: @if {m.group(1)} - not given on the command line")
            keep.append(defs[m.group(1)])
            continue
        if ENDIF_RE.match(line):
            if not keep:
                sys.exit(f"{path}:{no}: @endif without @if")
            keep.pop()
            continue
        if not all(keep):
            continue
        s = line.lstrip()
        for open_, close in (("/*", "*/"), ("<!--", "-->")):
            if s.startswith(open_):
                rest = s[len(open_):]
                if close in rest:
                    if not rest.rstrip().endswith(close):
                        break                    # shares the line with code: content
                    line = None
                else:
                    skip_until = close
                    line = None
                break
        if line is not None:
            out.append(line)
    if keep:
        sys.exit(f"{path}: @if without @endif")
    if skip_until:
        sys.exit(f"{path}: comment not closed")
    return "".join(out)


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    src, out_h, out_html = sys.argv[1:4]
    defs = {}
    for a in sys.argv[4:]:
        k, _, v = a.partition("=")
        defs[k] = v not in ("", "0", "OFF", "off", "FALSE", "false")
    with open(src, encoding="utf-8", newline="") as f:
        lines = f.read().replace("\r\n", "\n").splitlines(keepends=True)
    page = strip(lines, defs, src).encode("utf-8")
    gz = gzip.compress(page, compresslevel=9, mtime=0)

    with open(out_html, "wb") as f:
        f.write(page)
    rows = [", ".join(f"0x{b:02x}" for b in gz[k:k + 16]) for k in range(0, len(gz), 16)]
    with open(out_h, "w", encoding="ascii", newline="\n") as f:
        f.write("/* Generated by tools/page_gz.py from web/index.html - do not edit. */\n")
        f.write(f"/* {len(page)} bytes of page, {len(gz)} gzip'd */\n")
        f.write("#ifndef WEB_PAGE_GZ_H\n#define WEB_PAGE_GZ_H\n#include <stdint.h>\n")
        f.write(f"#define HTTP_INDEX_PAGE_RAW_LEN {len(page)}u\n")
        f.write("static const uint8_t HTTP_INDEX_PAGE_GZ[] = {\n    ")
        f.write(",\n    ".join(rows))
        f.write("\n};\n#endif\n")
    print(f"page_gz: {src} -> {len(page)} bytes, gzip {len(gz)}")


if __name__ == "__main__":
    main()
