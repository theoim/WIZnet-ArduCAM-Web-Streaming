#!/usr/bin/env bash
# Make the HTTPS certificate for camera_stream_https.
#
#   ./make_https_cert.sh [ip]          default ip 192.168.11.7
#
# Two things are produced, kept in two different places on purpose:
#
#   ~/.camera-stream-ca/ca.key, ca.crt   the demo certificate authority. Created
#                                        once and reused, so a browser that
#                                        trusts it keeps trusting every new
#                                        device certificate. OUTSIDE the
#                                        repository: whoever has ca.key can make
#                                        any certificate your browser accepts.
#   tls/https_cert.c                     the device key and certificate (signed
#                                        by that CA, subjectAltName = the IP),
#                                        as C arrays. git-ignored: it holds a
#                                        private key.
#
# Then trust the CA once on the viewing PC (current user only, no admin):
#   certutil -addstore -user Root "%USERPROFILE%\.camera-stream-ca\ca.crt"
# Chrome and Edge use that store; Firefox keeps its own (Settings > Privacy >
# Certificates > Import).

set -euo pipefail
export MSYS_NO_PATHCONV=1          # Git Bash would rewrite "/CN=..." into a path

IP="${1:-192.168.11.7}"
# With path conversion off, hand Windows tools (openssl, python) C:/... paths.
winpath() { if command -v cygpath >/dev/null 2>&1; then cygpath -m "$1"; else echo "$1"; fi; }
HERE="$(winpath "$(cd "$(dirname "$0")" && pwd)")"
CA_DIR="$(winpath "${HOME}")/.camera-stream-ca"
OUT_C="${HERE}/https_cert.c"
WORK="$(winpath "$(mktemp -d)")"
trap 'rm -rf "$WORK"' EXIT

mkdir -p "$CA_DIR"
if [ ! -f "$CA_DIR/ca.key" ]; then
    echo "creating demo CA in $CA_DIR"
    openssl ecparam -name prime256v1 -genkey -noout -out "$CA_DIR/ca.key"
    openssl req -new -x509 -key "$CA_DIR/ca.key" -out "$CA_DIR/ca.crt" -days 3650 \
        -subj "/CN=WIZnet camera-stream demo CA" \
        -addext "basicConstraints=critical,CA:TRUE" \
        -addext "keyUsage=critical,keyCertSign,cRLSign"
    chmod 600 "$CA_DIR/ca.key"
else
    echo "reusing demo CA in $CA_DIR"
fi

cd "$WORK"
openssl ecparam -name prime256v1 -genkey -noout -out dev.key
openssl req -new -key dev.key -out dev.csr -subj "/CN=camera-stream ${IP}"
cat > ext.cnf <<EOF
basicConstraints=CA:FALSE
keyUsage=critical,digitalSignature
extendedKeyUsage=serverAuth
subjectAltName=IP:${IP}
EOF
# Browsers refuse server certificates valid for more than ~398 days.
openssl x509 -req -in dev.csr -CA "$CA_DIR/ca.crt" -CAkey "$CA_DIR/ca.key" \
    -CAcreateserial -out dev.crt -days 397 -sha256 -extfile ext.cnf
openssl x509 -in dev.crt -outform DER -out dev.der
openssl x509 -in "$CA_DIR/ca.crt" -outform DER -out ca.der
openssl ec -in dev.key -outform DER -out dev_key.der 2>/dev/null

python - "$OUT_C" "$WORK" "$IP" <<'PY'
import sys, os
out, work, ip = sys.argv[1], sys.argv[2], sys.argv[3]
def arr(name, fn):
    b = open(os.path.join(work, fn), 'rb').read()
    rows = [', '.join(f'0x{x:02x}' for x in b[i:i+12]) for i in range(0, len(b), 12)]
    return (f"const unsigned char {name}[] = {{\n    " + ",\n    ".join(rows) +
            f"\n}};\nconst unsigned int {name}_len = {len(b)};\n")
open(out, 'w').write(
    "/* GENERATED by tls/make_https_cert.sh - do not commit (holds a private key).\n"
    f" * Device certificate for {ip}, signed by the demo CA in ~/.camera-stream-ca. */\n\n"
    + arr('https_dev_cert_der', 'dev.der') + "\n"
    + arr('https_ca_cert_der', 'ca.der') + "\n"
    + arr('https_dev_key_der', 'dev_key.der'))
print("wrote", out)
PY

echo
echo "device certificate for IP ${IP}:"
openssl x509 -in dev.crt -noout -subject -issuer -enddate -ext subjectAltName
